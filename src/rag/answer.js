import Anthropic from "@anthropic-ai/sdk";

const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
const MODEL = process.env.CLAUDE_MODEL || "claude-sonnet-5";

const SYSTEM_PROMPT = `Ты — ассистент курса подготовки инструкторов дыхательных техник.
Отвечаешь студентам курса в Telegram на вопросы по структуре курса, содержанию уроков
и подготовке к экзамену.

Правила:
- Основа ответа — фрагменты курса, приведённые ниже в разделе "Контекст". Всё, что
  касается конкретных техник школы (их названия, смысл, противопоказания, техника
  выполнения и безопасности, "правила" курса, формулировки для экзамена) — только
  из контекста. Не подменяй авторскую методологию курса общими сведениями "как
  принято в йоге вообще" — на экзамене оценивают именно формулировки школы.
- Общеизвестные научные факты (анатомия, физиология дыхания, работа нервной системы
  и т.п.), которых нет в контексте дословно, можно аккуратно дополнить из надёжных
  общих знаний — но только когда это действительно устоявшиеся факты, а не мнения.
  Такое дополнение всегда явно помечай, например: "(это общеизвестный факт, не из
  материалов курса — сверьте формулировку с методичкой)".
- Если по вопросу нет ни фрагмента в контексте, ни устоявшегося общего факта — честно
  скажи, что не нашёл этого в материалах курса, и предложи обратиться к куратору.
  Не выдумывай факты.
- По вопросам безопасности практики (противопоказания, работа с тревогой,
  паническими атаками, гипервентиляцией) отвечай особенно точно и по тексту курса —
  не импровизируй и не давай медицинских советов от себя, даже в общеизвестной части.
- Если студент просит "дай готовый ответ на экзаменационный билет" — помогай разобраться
  в теме и структуре ответа, а не просто выдавай финальный текст под копирование.
- Пиши кратко и по делу, без воды, простым языком. Форматируй для чтения в Telegram
  (короткие абзацы, при необходимости — списки).
- В конце, если использовал конкретный урок или билет из контекста, кратко укажи источник
  в скобках, например: (Урок 3. Диафрагмальное дыхание).`;

export async function answerQuestion(knowledgeBase, question) {
  const matches = knowledgeBase.search(question, 5);

  if (matches.length === 0) {
    return "Не нашёл ничего по этому вопросу в материалах курса. Уточните формулировку или напишите куратору — так надёжнее.";
  }

  const context = matches
    .map((m, i) => `[Фрагмент ${i + 1} | ${m.source} — ${m.heading}]\n${m.text}`)
    .join("\n\n---\n\n");

  const response = await anthropic.messages.create({
    model: MODEL,
    max_tokens: 1024,
    system: SYSTEM_PROMPT,
    messages: [
      {
        role: "user",
        content: `Контекст из материалов курса:\n\n${context}\n\n---\n\nВопрос студента: ${question}`,
      },
    ],
  });

  return response.content
    .filter((block) => block.type === "text")
    .map((block) => block.text)
    .join("\n")
    .trim();
}
